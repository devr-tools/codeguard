func TestPythonToolchainDeadCodeReportsUnreachableModules(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "app", "__init__.py"), "")
	writeFile(t, filepath.Join(dir, "app", "__main__.py"), `from app.live import run

run()
`)
	writeFile(t, filepath.Join(dir, "app", "live.py"), `def run():
    return "ok"
`)
	writeFile(t, filepath.Join(dir, "app", "orphan.py"), `def cleanup():
    return "legacy"
`)

	report := runPythonToolchainDeadCodeScan(t, dir, true)

	assertToolchainDeadCodePath(t, report, "app/orphan.py")
	assertToolchainDeadCodeFindingPathAbsent(t, report, "app/live.py")
}

func TestPythonToolchainDeadCodeAvoidsKnownFalsePositives(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "app", "__init__.py"), "")
	writeFile(t, filepath.Join(dir, "app", "__main__.py"), `from app.live import run

run()
`)
	writeFile(t, filepath.Join(dir, "app", "live.py"), `def run():
    return "ok"
`)
	writeFile(t, filepath.Join(dir, "app", "dynamic.py"), `import importlib

handler = importlib.import_module("app.handlers")
`)
	writeFile(t, filepath.Join(dir, "app", "routes.py"), `@app.route("/health")
def health():
    return "ok"
`)
	writeFile(t, filepath.Join(dir, "tests", "test_helpers.py"), `def test_only_helper():
    return "test"
`)
	writeFile(t, filepath.Join(dir, "app", "generated.py"), `# Code generated by test fixture. DO NOT EDIT.
def generated_helper():
    return "generated"
`)
	writeFile(t, filepath.Join(dir, "app", "ignored", "legacy.py"), `def ignored():
    return "ignored"
`)

	report := runPythonToolchainDeadCodeScanWithConfig(t, dir, true, func(cfg *codeguard.Config) {
		cfg.Checks.QualityRules.DeadCode.Python.IgnorePaths = []string{"app/ignored/**"}
	})

	assertFindingRuleAbsent(t, report, "Code Quality", "quality.dead-code.toolchain")
}

