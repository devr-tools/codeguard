func TestPythonToolchainDeadCodeTreatsDynamicImportsExportsAndFrameworkFilesAsLive(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "setup.cfg"), `[options.entry_points]
console_scripts =
    worker = app.loader:main
`)
	writeFile(t, filepath.Join(dir, "app", "__init__.py"), `from . import public

__all__ = ["public"]
`)
	writeFile(t, filepath.Join(dir, "app", "loader.py"), `import importlib

def main():
    return importlib.import_module("app.plugin")
`)
	writeFile(t, filepath.Join(dir, "app", "plugin.py"), `def activate():
    return "plugin"
`)
	writeFile(t, filepath.Join(dir, "app", "public.py"), `def facade():
    return "public"
`)
	writeFile(t, filepath.Join(dir, "app", "views.py"), `from django.urls import path

urlpatterns = [path("health", lambda request: "ok")]
`)
	writeFile(t, filepath.Join(dir, "app", "orphan.py"), `def cleanup():
    return "legacy"
`)

	report := runPythonToolchainDeadCodeScanWithConfig(t, dir, true, func(cfg *codeguard.Config) {
		cfg.Targets[0].Entrypoints = nil
	})

	assertToolchainDeadCodePath(t, report, "app/orphan.py")
	assertToolchainDeadCodeFindingPathAbsent(t, report, "app/loader.py")
	assertToolchainDeadCodeFindingPathAbsent(t, report, "app/plugin.py")
	assertToolchainDeadCodeFindingPathAbsent(t, report, "app/public.py")
	assertToolchainDeadCodeFindingPathAbsent(t, report, "app/views.py")
}

