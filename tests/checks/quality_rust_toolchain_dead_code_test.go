func writeRustToolchainCrate(t *testing.T, dir string) {
	t.Helper()
	writeFile(t, filepath.Join(dir, "Cargo.toml"), `[package]
name = "rust-dead-code-test"
version = "0.1.0"
edition = "2021"
`)
	writeFile(t, filepath.Join(dir, "src", "lib.rs"), `pub fn used() {}

fn unused_private() {}

pub fn exported_api() {}
`)
}

func rustToolchainDeadCodeConfig(dir string, enabled bool) codeguard.Config {
	cfg := codeguard.ExampleConfig()
	cfg.Name = "rust-toolchain-dead-code-test"
	cfg.Targets = []codeguard.TargetConfig{{Name: "repo", Path: dir, Language: "rust"}}
	cfg.Checks.Quality = true
	cfg.Checks.Design = false
	cfg.Checks.Security = false
	cfg.Checks.Prompts = false
	cfg.Checks.CI = false
	cfg.Checks.Performance = boolValue(false)
	cfg.Checks.SupplyChain = false
	cfg.Checks.Delivery = boolValue(false)
	cfg.Checks.Reliability = boolValue(false)
	cfg.Checks.Data = boolValue(false)
	cfg.Checks.Observability = boolValue(false)
	cfg.Checks.Operations = boolValue(false)
	cfg.Checks.Change = boolValue(false)
	cfg.Checks.Contracts = boolValue(false)
	cfg.Checks.Context = boolValue(false)
	cfg.Checks.QualityRules.AIChecks.DeadCode = boolValue(false)
	cfg.Cache.Enabled = boolValue(false)
	if enabled {
		cfg.Checks.QualityRules.DeadCode.Enabled = boolValue(true)
		cfg.Checks.QualityRules.DeadCode.Mode = "toolchain"
		cfg.Checks.QualityRules.DeadCode.Level = "warn"
	}
	return cfg
}

func installFakeCargo(t *testing.T, output string) {
	t.Helper()
	binDir := t.TempDir()
	writeExecutableFile(t, filepath.Join(binDir, "cargo"), "#!/bin/sh\ncat <<'JSON'\n"+output+"\nJSON\nexit 1\n")
	t.Setenv("PATH", binDir+string(os.PathListSeparator)+os.Getenv("PATH"))
}

func installFakeCargoSuccess(t *testing.T) {
	t.Helper()
	binDir := t.TempDir()
	writeExecutableFile(t, filepath.Join(binDir, "cargo"), "#!/bin/sh\nexit 0\n")
	t.Setenv("PATH", binDir+string(os.PathListSeparator)+os.Getenv("PATH"))
}
