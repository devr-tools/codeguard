func TestRustToolchainDeadCodeIsOptIn(t *testing.T) {
	dir := t.TempDir()
	writeRustToolchainCrate(t, dir)
	installFakeCargo(t, `{"reason":"compiler-message","message":{"level":"error","message":"function `+"`unused_private`"+` is never used","code":{"code":"dead_code"},"spans":[{"file_name":"src/lib.rs","line_start":3,"column_start":4,"is_primary":true}]}}`)

	report := runScan(t, rustToolchainDeadCodeConfig(dir, false))

	assertFindingRuleAbsent(t, report, "Code Quality", goToolchainDeadCodeRuleID)
}

func TestRustToolchainDeadCodeReportsCargoDeadCodeDiagnostics(t *testing.T) {
	dir := t.TempDir()
	writeRustToolchainCrate(t, dir)
	installFakeCargo(t, `{"reason":"compiler-message","message":{"level":"error","message":"function `+"`unused_private`"+` is never used","code":{"code":"dead_code"},"spans":[{"file_name":"src/lib.rs","line_start":3,"column_start":4,"is_primary":true}]}}
{"reason":"compiler-message","message":{"level":"error","message":"function `+"`exported_api`"+` is never used","code":{"code":"dead_code"},"spans":[{"file_name":"src/lib.rs","line_start":5,"column_start":1,"is_primary":true}]}}
{"reason":"compiler-message","message":{"level":"warning","message":"unused variable","code":{"code":"unused_variables"},"spans":[{"file_name":"src/lib.rs","line_start":7,"column_start":9,"is_primary":true}]}}`)

	report := runScan(t, rustToolchainDeadCodeConfig(dir, true))
	findings := findingsForRule(report, goToolchainDeadCodeRuleID)

	if len(findings) != 1 {
		t.Fatalf("toolchain dead-code findings = %d, want 1: %+v", len(findings), findings)
	}
	if findings[0].Path != "src/lib.rs" || findings[0].Line != 3 {
		t.Fatalf("finding = %+v, want private src/lib.rs:3 diagnostic", findings[0])
	}
}

func TestRustToolchainDeadCodeReportsArtifactReachability(t *testing.T) {
	dir := t.TempDir()
	writeRustToolchainCrate(t, dir)
	writeFile(t, filepath.Join(dir, ".codeguard", "rust-symbols.txt"), `00000000 T rust_dead_code_test::used
`)
	installFakeCargoSuccess(t)

	cfg := rustToolchainDeadCodeConfig(dir, true)
	cfg.Checks.QualityRules.DeadCode.Rust.Reports = []string{".codeguard/rust-symbols.txt"}
	report := runScan(t, cfg)
	findings := findingsForRule(report, goToolchainDeadCodeRuleID)

	if len(findings) != 1 {
		t.Fatalf("toolchain dead-code findings = %d, want 1: %+v", len(findings), findings)
	}
	if findings[0].Path != "src/lib.rs" || findings[0].Line != 3 {
		t.Fatalf("finding = %+v, want artifact finding for src/lib.rs:3", findings[0])
	}
	if findings[0].Metadata["evidence"] != "artifact-symbol-report" {
		t.Fatalf("metadata = %+v, want artifact evidence", findings[0].Metadata)
	}
}

