package checks_test

import (
	"context"
	"path/filepath"
	"testing"

	"github.com/devr-tools/codeguard/pkg/codeguard"
)

// yarnBerryLock is shaped like a real Yarn 2+ lockfile: a `__metadata` header,
// YAML-style `version:` fields, `npm:` protocol selectors, a `patch:` entry and
// the workspace root entry.
const yarnBerryLock = `# This file is generated by running "yarn install" inside your project.
# Manual changes might be lost - proceed with caution!

__metadata:
  version: 8
  cacheKey: 10c0

"@linear/sdk@npm:^2.6.0":
  version: 2.6.0
  resolution: "@linear/sdk@npm:2.6.0"
  dependencies:
    "@linear/import": "npm:^1.0.0"
  checksum: 10c0/deadbeef
  languageName: node
  linkType: hard

"fsevents@patch:fsevents@npm%3A2.3.2#optional!builtin<compat/fsevents>":
  version: 2.3.2
  resolution: "fsevents@patch:fsevents@npm%3A2.3.2#optional!builtin<compat/fsevents>::version=2.3.2&hash=df0bf1"
  languageName: node
  linkType: hard

"left-pad@npm:^1.3.0":
  version: 1.3.0
  resolution: "left-pad@npm:1.3.0"
  checksum: 10c0/cafebabe
  languageName: node
  linkType: hard

"shared-utils@workspace:packages/utils":
  version: 0.0.0-use.local
  resolution: "shared-utils@workspace:packages/utils"
  languageName: unknown
  linkType: soft

"typescript@npm:^5.5.4":
  version: 5.5.4
  resolution: "typescript@npm:5.5.4"
  languageName: node
  linkType: hard

"workspace-root@workspace:.":
  version: 0.0.0-use.local
  resolution: "workspace-root@workspace:."
  languageName: unknown
  linkType: soft
`

// yarnClassicLock is shaped like a real Yarn v1 lockfile: quoted selectors with
// no protocol and `version "x"` fields.
const yarnClassicLock = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@linear/sdk@^2.6.0":
  version "2.6.0"
  resolved "https://registry.yarnpkg.com/@linear/sdk/-/sdk-2.6.0.tgz#deadbeef"
  integrity sha512-deadbeef==
  dependencies:
    "@linear/import" "^1.0.0"

left-pad@^1.3.0:
  version "1.3.0"
  resolved "https://registry.yarnpkg.com/left-pad/-/left-pad-1.3.0.tgz#cafebabe"
  integrity sha512-cafebabe==

typescript@^5.5.4:
  version "5.5.4"
  resolved "https://registry.yarnpkg.com/typescript/-/typescript-5.5.4.tgz#abc123"
  integrity sha512-abc123==
`

func TestSupplyChainLockfileParsing(t *testing.T) {
	nodeManifest := `{
  "name": "frontend",
  "dependencies": {
    "@linear/sdk": "^2.6.0",
    "left-pad": "^1.3.0"
  },
  "devDependencies": {
    "typescript": "^5.5.4"
  }
}`

	pyprojectManifest := `[tool.poetry]
name = "backend"
version = "0.1.0"
license = "MIT"

[tool.poetry.dependencies]
python = ">=3.10,<3.13"
Jinja2 = "^3.1.0"
Markdown = "^3.5.0"
typing_extensions = "^4.12.0"
zope.interface = "^6.0"

[tool.poetry.group.dev.dependencies]
pytest = "^8.0.0"
`

	// poetry.lock records PEP 503-normalised names; the manifest above keeps the
	// author's mixed-case and underscored spellings.
	poetryLock := `# This file is automatically @generated by Poetry 2.4.1 and should not be changed by hand.

[[package]]
name = "jinja2"
version = "3.1.4"
description = "A very fast and expressive template engine."
optional = false
python-versions = ">=3.7"
groups = ["main"]

[[package]]
name = "markdown"
version = "3.7"
description = "Python implementation of John Gruber's Markdown."
optional = false
python-versions = ">=3.8"
groups = ["main"]

[[package]]
name = "typing-extensions"
version = "4.12.2"
description = "Backported and Experimental Type Hints for Python 3.8+"
optional = false
python-versions = ">=3.8"
groups = ["main"]

[[package]]
name = "zope-interface"
version = "6.4.post2"
description = "Interfaces for Python"
optional = false
python-versions = ">=3.7"
groups = ["main"]

[[package]]
name = "pytest"
version = "8.3.3"
description = "pytest: simple powerful testing with Python"
optional = false
python-versions = ">=3.8"
groups = ["dev"]

[metadata]
lock-version = "2.1"
python-versions = ">=3.10,<3.13"
content-hash = "deadbeef"
`

	cases := []struct {
		name  string
		files map[string]string
		want  []string
	}{
		{
			name: "yarn berry resolves every dependency",
			files: map[string]string{
				"package.json": nodeManifest,
				"yarn.lock":    yarnBerryLock,
			},
			want: nil,
		},
		{
			name: "yarn berry still reports a genuinely missing dependency",
			files: map[string]string{
				"package.json": nodeManifest,
				"yarn.lock": `__metadata:
  version: 8

"@linear/sdk@npm:^2.6.0":
  version: 2.6.0
  resolution: "@linear/sdk@npm:2.6.0"

"typescript@npm:^5.5.4":
  version: 5.5.4
  resolution: "typescript@npm:5.5.4"
`,
			},
			want: []string{"dependency left-pad is not present in yarn.lock"},
		},
		{
			name: "yarn classic resolves every dependency",
			files: map[string]string{
				"package.json": nodeManifest,
				"yarn.lock":    yarnClassicLock,
			},
			want: nil,
		},
		{
			name: "pnpm lockfile v9 resolves every dependency",
			files: map[string]string{
				"package.json": nodeManifest,
				"pnpm-lock.yaml": `lockfileVersion: '9.0'

importers:
  .:
    dependencies:
      '@linear/sdk':
        specifier: ^2.6.0
        version: 2.6.0

packages:
  '@linear/sdk@2.6.0':
    resolution: {integrity: sha512-deadbeef==}
  left-pad@1.3.0:
    resolution: {integrity: sha512-cafebabe==}
  typescript@5.5.4:
    resolution: {integrity: sha512-abc123==}
`,
			},
			want: nil,
		},
		{
			name: "pnpm lockfile v5 slash keys resolve every dependency",
			files: map[string]string{
				"package.json": nodeManifest,
				"pnpm-lock.yaml": `lockfileVersion: 5.4

specifiers:
  '@linear/sdk': ^2.6.0

packages:

  /@linear/sdk/2.6.0:
    resolution: {integrity: sha512-deadbeef==}
    dev: false

  /left-pad/1.3.0_react@18.2.0:
    resolution: {integrity: sha512-cafebabe==}
    dev: false

  /typescript/5.5.4:
    resolution: {integrity: sha512-abc123==}
    dev: true
`,
			},
			want: nil,
		},
		{
			name: "package-lock v3 resolves every dependency",
			files: map[string]string{
				"package.json": nodeManifest,
				"package-lock.json": `{
  "name": "frontend",
  "lockfileVersion": 3,
  "requires": true,
  "packages": {
    "": {"name": "frontend"},
    "node_modules/@linear/sdk": {"version": "2.6.0"},
    "node_modules/left-pad": {"version": "1.3.0"},
    "node_modules/typescript": {"version": "5.5.4", "dev": true}
  }
}`,
			},
			want: nil,
		},
		{
			name: "poetry lock matches PEP 503 normalised names",
			files: map[string]string{
				"pyproject.toml": pyprojectManifest,
				"poetry.lock":    poetryLock,
			},
			want: nil,
		},
		{
			name: "poetry lock still reports a genuinely missing dependency",
			files: map[string]string{
				"pyproject.toml": pyprojectManifest,
				"poetry.lock": `# This file is automatically @generated by Poetry and should not be changed by hand.

[[package]]
name = "jinja2"
version = "3.1.4"

[[package]]
name = "typing-extensions"
version = "4.12.2"

[[package]]
name = "zope-interface"
version = "6.4.post2"

[[package]]
name = "pytest"
version = "8.3.3"

[metadata]
lock-version = "2.1"
`,
			},
			want: []string{"dependency Markdown is not present in poetry.lock"},
		},
		{
			name: "npm names are not normalised across separators or case",
			files: map[string]string{
				"package.json": `{"dependencies": {"Left_Pad": "^1.3.0"}}`,
				"package-lock.json": `{
  "lockfileVersion": 3,
  "packages": {
    "": {"name": "frontend"},
    "node_modules/left-pad": {"version": "1.3.0"}
  }
}`,
			},
			want: []string{"dependency Left_Pad is not present in package-lock.json"},
		},
		{
			name: "unparseable yarn lockfile reports nothing",
			files: map[string]string{
				"package.json": nodeManifest,
				"yarn.lock": `<<<<<<< HEAD
this file was mangled by a bad merge and is not a lockfile
=======
neither is this half
>>>>>>> feature
`,
			},
			want: nil,
		},
		{
			name: "unparseable poetry lockfile reports nothing",
			files: map[string]string{
				"pyproject.toml": pyprojectManifest,
				"poetry.lock": `this poetry.lock was truncated during a rebase
and holds no package tables at all
`,
			},
			want: nil,
		},
		{
			name: "empty poetry lockfile is compared rather than skipped",
			files: map[string]string{
				"pyproject.toml": `[tool.poetry]
name = "backend"

[tool.poetry.dependencies]
Jinja2 = "^3.1.0"
`,
				"poetry.lock": `# This file is automatically @generated by Poetry and should not be changed by hand.
package = []

[metadata]
lock-version = "2.1"
content-hash = "deadbeef"
`,
			},
			want: []string{"dependency Jinja2 is not present in poetry.lock"},
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			for name, content := range tc.files {
				writeFile(t, filepath.Join(dir, name), content)
			}

			report, err := codeguard.Run(context.Background(), supplyChainTestConfig(dir, "lockfile-parsing"))
			if err != nil {
				t.Fatalf("run: %v", err)
			}

			got := supplyChainRuleMessages(report, "supply_chain.lockfile-drift")
			if len(got) != len(tc.want) {
				t.Fatalf("lockfile-drift findings = %v, want %v", got, tc.want)
			}
			for idx, want := range tc.want {
				if got[idx] != want {
					t.Fatalf("lockfile-drift finding %d = %q, want %q", idx, got[idx], want)
				}
			}
		})
	}
}
