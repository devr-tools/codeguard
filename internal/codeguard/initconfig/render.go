package initconfig

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/devr-tools/codeguard/internal/codeguard/core"
	"github.com/devr-tools/codeguard/internal/version"
)

// ChecksReference is where the generated config points readers for every
// setting it leaves at its default.
const ChecksReference = "https://github.com/devr-tools/codeguard/blob/main/docs/checks.md"

// starterDocument is the on-disk shape of the small config. It mirrors the
// matching core.Config keys but omits everything init does not decide, so
// the file states only what was detected.
type starterDocument struct {
	CodeguardVersion string          `json:"codeguard_version,omitempty" yaml:"codeguard_version,omitempty"`
	Name             string          `json:"name,omitempty" yaml:"name,omitempty"`
	Profile          string          `json:"profile,omitempty" yaml:"profile,omitempty"`
	Targets          []starterTarget `json:"targets" yaml:"targets"`
	Checks           starterChecks   `json:"checks" yaml:"checks"`
}

type starterTarget struct {
	Name        string   `json:"name" yaml:"name"`
	Path        string   `json:"path" yaml:"path"`
	Language    string   `json:"language,omitempty" yaml:"language,omitempty"`
	Entrypoints []string `json:"entrypoints,omitempty" yaml:"entrypoints,omitempty"`
}

type starterChecks struct {
	Quality     bool `json:"quality" yaml:"quality"`
	Performance bool `json:"performance" yaml:"performance"`
	Design      bool `json:"design" yaml:"design"`
	Security    bool `json:"security" yaml:"security"`
	Prompts     bool `json:"prompts" yaml:"prompts"`
	CI          bool `json:"ci" yaml:"ci"`
	SupplyChain bool `json:"supply_chain" yaml:"supply_chain"`
}

// Render serializes a config produced by Build as the small starter file.
// The format follows the extension of path (.yaml/.yml, otherwise JSON); YAML
// output carries a header comment summarizing what was detected and pointing
// at docs/checks.md for every other setting.
func Render(path string, cfg core.Config, layout Layout) ([]byte, error) {
	doc := starterDocument{
		CodeguardVersion: version.Number,
		Name:             cfg.Name,
		Profile:          cfg.Profile,
		Targets:          make([]starterTarget, 0, len(cfg.Targets)),
		Checks: starterChecks{
			Quality:     cfg.Checks.Quality,
			Performance: cfg.Checks.Performance != nil && *cfg.Checks.Performance,
			Design:      cfg.Checks.Design,
			Security:    cfg.Checks.Security,
			Prompts:     cfg.Checks.Prompts,
			CI:          cfg.Checks.CI,
			SupplyChain: cfg.Checks.SupplyChain,
		},
	}
	for _, target := range cfg.Targets {
		doc.Targets = append(doc.Targets, starterTarget{
			Name:        target.Name,
			Path:        target.Path,
			Language:    target.Language,
			Entrypoints: target.Entrypoints,
		})
	}

	switch strings.ToLower(filepath.Ext(path)) {
	case ".yaml", ".yml":
		var body bytes.Buffer
		body.WriteString(yamlHeader(layout))
		encoder := yaml.NewEncoder(&body)
		encoder.SetIndent(2)
		if err := encoder.Encode(doc); err != nil {
			return nil, err
		}
		if err := encoder.Close(); err != nil {
			return nil, err
		}
		return body.Bytes(), nil
	default:
		body, err := json.MarshalIndent(doc, "", "  ")
		if err != nil {
			return nil, err
		}
		return append(body, '\n'), nil
	}
}

func yamlHeader(layout Layout) string {
	lines := []string{
		"# codeguard configuration, generated by `codeguard init` from this repository.",
		"#",
		"# It sets only what init detected: the targets and which check sections run.",
		"# Every other setting uses its built-in default. See docs/checks.md for all",
		"# options and rules: " + ChecksReference,
		"# (`codeguard init -full` writes every setting with its resolved value instead.)",
		"#",
	}
	for _, line := range DescribeLayout(layout) {
		lines = append(lines, "# "+line)
	}
	return strings.Join(lines, "\n") + "\n"
}

// DescribeLayout renders a short, human-readable detection summary, used both
// in the generated file's header and in `codeguard init` output.
func DescribeLayout(layout Layout) []string {
	lines := make([]string, 0, 4+len(layout.Languages))
	if len(layout.Languages) == 0 {
		lines = append(lines, "detected languages: none recognized (one language-less target)")
	} else {
		parts := make([]string, 0, len(layout.Languages))
		for _, lang := range layout.Languages {
			parts = append(parts, fmt.Sprintf("%s (%s)", lang.Language, pluralFiles(lang.Files)))
		}
		lines = append(lines, "detected languages: "+strings.Join(parts, ", "))
	}
	if len(layout.Minor) > 0 {
		parts := make([]string, 0, len(layout.Minor))
		for _, lang := range layout.Minor {
			parts = append(parts, fmt.Sprintf("%s (%s)", lang.Language, pluralFiles(lang.Files)))
		}
		lines = append(lines, "too few files for a target: "+strings.Join(parts, ", "))
	}
	for _, lang := range layout.Languages {
		if len(lang.Entrypoints) > 0 {
			lines = append(lines, fmt.Sprintf("%s entrypoints: %s", lang.Language, strings.Join(lang.Entrypoints, ", ")))
		}
	}
	if len(layout.Workflows) > 0 {
		lines = append(lines, fmt.Sprintf("ci: enabled (%d GitHub Actions workflow(s) in .github/workflows)", len(layout.Workflows)))
	} else {
		lines = append(lines, "ci: disabled (no .github/workflows directory)")
	}
	if len(layout.Manifests) > 0 {
		lines = append(lines, "supply_chain: enabled (manifests: "+summarizeList(layout.Manifests, 5)+")")
	} else {
		lines = append(lines, "supply_chain: disabled (no package manifests found)")
	}
	return lines
}

func pluralFiles(n int) string {
	if n == 1 {
		return "1 file"
	}
	return fmt.Sprintf("%d files", n)
}

func summarizeList(items []string, limit int) string {
	if len(items) <= limit {
		return strings.Join(items, ", ")
	}
	return fmt.Sprintf("%s, and %d more", strings.Join(items[:limit], ", "), len(items)-limit)
}

// WriteFile writes rendered starter config data to path, creating parent
// directories as needed.
func WriteFile(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil && !errors.Is(err, os.ErrExist) {
		return err
	}
	return os.WriteFile(path, data, 0o600)
}
