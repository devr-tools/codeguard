package contextgen

import (
	"fmt"
	"strings"
)

// Block names, in render order. Each is one codeguard-managed region.
const (
	BlockOverview    = "overview"
	BlockCommands    = "commands"
	BlockLayout      = "layout"
	BlockEntrypoints = "entrypoints"
	BlockTests       = "tests"
	BlockConventions = "conventions"
)

// managedBlock is one codeguard-managed region: the heading rendered above it
// (outside the markers, so a human may rename it), the body renderer, and a
// TODO left below it for what detection cannot know.
type managedBlock struct {
	name    string
	heading string
	body    func(Facts) []string
	todo    string
}

var managedBlocks = []managedBlock{
	{BlockOverview, "", overviewBody, "TODO: describe what this project does, who uses it, and anything an agent must never do here."},
	{BlockCommands, "Commands", commandsBody, ""},
	{BlockLayout, "Layout", layoutBody, ""},
	{BlockEntrypoints, "Entrypoints", entrypointsBody, ""},
	{BlockTests, "Tests", testsBody, ""},
	{BlockConventions, "Conventions", conventionsBody, "TODO: add conventions codeguard cannot detect (naming, error handling, review expectations)."},
}

// BlockNames returns the managed block names in render order.
func BlockNames() []string {
	names := make([]string, 0, len(managedBlocks))
	for _, block := range managedBlocks {
		names = append(names, block.name)
	}
	return names
}

// BeginMarker and EndMarker return the comment lines delimiting a managed
// block.
func BeginMarker(name string) string { return "<!-- codeguard:begin " + name + " -->" }

// EndMarker returns the comment line closing a managed block.
func EndMarker(name string) string { return "<!-- codeguard:end " + name + " -->" }

const generatedNotice = "<!-- Generated by `codeguard context init`. `codeguard context update` refreshes only the text between codeguard:begin/end markers; edit everything else freely. -->"

// Render writes a complete agent instruction file from facts.
func Render(facts Facts) string {
	var b strings.Builder
	b.WriteString("# " + facts.Name + "\n\n")
	b.WriteString(generatedNotice + "\n")
	for _, block := range managedBlocks {
		writeSection(&b, block, facts)
	}
	return b.String()
}

// RenderSections writes every managed section (heading, markers, body and
// TODO) without the document title, for appending to an existing file.
func RenderSections(facts Facts) string {
	var b strings.Builder
	for _, block := range managedBlocks {
		if block.heading == "" {
			b.WriteString("\n## Overview\n")
		}
		writeSection(&b, block, facts)
	}
	return b.String()
}

func writeSection(b *strings.Builder, block managedBlock, facts Facts) {
	b.WriteString("\n")
	if block.heading != "" {
		b.WriteString("## " + block.heading + "\n\n")
	}
	b.WriteString(BeginMarker(block.name) + "\n")
	b.WriteString(blockBody(block, facts))
	b.WriteString(EndMarker(block.name) + "\n")
	if block.todo != "" {
		b.WriteString("\n" + block.todo + "\n")
	}
}

// blockBody renders a block's content lines, each newline-terminated.
func blockBody(block managedBlock, facts Facts) string {
	lines := block.body(facts)
	if len(lines) == 0 {
		return ""
	}
	return strings.Join(lines, "\n") + "\n"
}

func overviewBody(facts Facts) []string {
	var lines []string
	if len(facts.Languages) == 0 {
		lines = append(lines, "- TODO: no source languages detected; state what this repository contains.")
	} else {
		parts := make([]string, 0, len(facts.Languages))
		for _, lang := range facts.Languages {
			parts = append(parts, fmt.Sprintf("%s (%s)", lang.Name, pluralize(lang.Files, "file")))
		}
		lines = append(lines, "- Languages, by source file count: "+strings.Join(parts, ", ")+".")
	}
	if len(facts.Manifests) > 0 {
		lines = append(lines, "- Package manifests: "+codeList(facts.Manifests)+".")
	}
	if len(facts.Workflows) > 0 {
		lines = append(lines, "- CI workflows: "+codeList(facts.Workflows)+".")
	}
	return lines
}

// commandsBody groups commands by source, preserving detection order.
func commandsBody(facts Facts) []string {
	if len(facts.Commands) == 0 {
		return []string{"- TODO: no build, test or lint commands detected; document how to build and test this project."}
	}
	lines := []string{"Run from the repository root."}
	var order []string
	bySource := map[string][]string{}
	for _, command := range facts.Commands {
		if _, ok := bySource[command.Source]; !ok {
			order = append(order, command.Source)
		}
		bySource[command.Source] = append(bySource[command.Source], command.Invocation)
	}
	for _, source := range order {
		lines = append(lines, "", sourceHeading(source)+":")
		for _, invocation := range bySource[source] {
			lines = append(lines, "- `"+invocation+"`")
		}
	}
	return lines
}

func sourceHeading(source string) string {
	switch source {
	case sourceMakefile:
		return "Makefile targets"
	case sourcePackageJSON:
		return "`package.json` scripts"
	case sourceGo:
		return "Go toolchain (`go.mod`)"
	case sourceCargo:
		return "Cargo (`Cargo.toml`)"
	case sourcePyproject:
		return "Tools configured in `pyproject.toml`"
	default:
		return "CI steps in `" + source + "`"
	}
}

func layoutBody(facts Facts) []string {
	if len(facts.Directories) == 0 {
		return []string{"- TODO: no top-level directories detected; describe the repository layout."}
	}
	lines := make([]string, 0, len(facts.Directories))
	for _, dir := range facts.Directories {
		if dir.Purpose != "" {
			lines = append(lines, fmt.Sprintf("- `%s`: %s (%s).", dir.Path, dir.Purpose, dir.Contents))
			continue
		}
		lines = append(lines, fmt.Sprintf("- `%s`: TODO: describe this directory (%s).", dir.Path, dir.Contents))
	}
	return lines
}

func entrypointsBody(facts Facts) []string {
	if len(facts.Entrypoints) == 0 {
		return []string{"- TODO: no entrypoints detected; name the binaries, servers or scripts this repository ships."}
	}
	lines := make([]string, 0, len(facts.Entrypoints))
	for _, entry := range facts.Entrypoints {
		lines = append(lines, fmt.Sprintf("- `%s` (%s)", entry.Path, entry.Language))
	}
	return lines
}

func testsBody(facts Facts) []string {
	if len(facts.Tests) == 0 {
		return []string{"- TODO: no test files detected; document how this project is tested."}
	}
	lines := make([]string, 0, len(facts.Tests))
	for _, loc := range facts.Tests {
		where := "the repository root"
		if loc.Path != "." {
			where = "`" + loc.Path + "`"
		}
		lines = append(lines, fmt.Sprintf("- %s: %s (%s).", where, pluralize(loc.Files, "test file"), strings.Join(loc.Languages, ", ")))
	}
	return lines
}

func conventionsBody(facts Facts) []string {
	if len(facts.Conventions) == 0 {
		return []string{"- TODO: no formatter, linter or toolchain configuration detected; document code-style conventions."}
	}
	lines := make([]string, 0, len(facts.Conventions))
	for _, convention := range facts.Conventions {
		lines = append(lines, "- "+convention)
	}
	return lines
}

func codeList(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, "`"+value+"`")
	}
	return strings.Join(quoted, ", ")
}
